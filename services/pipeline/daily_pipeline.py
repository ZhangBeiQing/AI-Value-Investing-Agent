PROJECT_ROOT = Path(__file__).resolve().parents[2]
SKILL_FLOW_CONFIG = (
    PROJECT_ROOT
    / "configs"
    / "prompt_flow"
    / "fixed_tracked"
    / "main_policy.md"
)
